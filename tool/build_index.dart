// Builds lib/src/index/cairn_index.g.dart, the knowledge the server ships with.
//
//   dart run tool/build_index.dart --cairn-ui ../cairn_ui --site ../cairn_site
//
// Sources, all read as plain source text (no network, no Flutter):
//   * cairn_ui: the public API of every component, the design tokens and the
//     theme, with the doc comments the library already carries;
//   * cairn_site: each component's quick start and variant snippets, the
//     documentation pages, blocks and templates.
//
// The result is one gzipped, base64-encoded JSON document compiled into the
// package, so `dart compile exe` produces a server that needs no data files.
import 'dart:convert';
import 'dart:io';

import 'package:args/args.dart';

import 'extract/cairn_ui_extractor.dart';
import 'extract/site_extractor.dart';

Future<void> main(List<String> argv) async {
  final ArgParser parser = ArgParser()
    ..addOption(
      'cairn-ui',
      help: 'Path to a cairn_ui checkout.',
      mandatory: true,
    )
    ..addOption('site', help: 'Path to a cairn_site checkout.', mandatory: true)
    ..addOption(
      'out',
      defaultsTo: 'lib/src/index/cairn_index.g.dart',
      help: 'Generated Dart file.',
    )
    ..addOption('json', help: 'Also write the raw JSON here (for inspection).');
  final ArgResults args = parser.parse(argv);

  final CairnUiExtractor ui = CairnUiExtractor(Directory(args['cairn-ui']));
  final SiteExtractor site = SiteExtractor(Directory(args['site']));

  final List<Map<String, Object?>> modules = ui.components();
  final Map<String, Object?> index = <String, Object?>{
    'cairnUiVersion': ui.version(),
    'modules': modules,
    'tokens': ui.tokens(),
    'components': site.componentEntries(),
    'docs': site.docPages(),
    'blocks': site.blocks(),
    'templates': site.templates(),
  };

  final String json = const JsonEncoder().convert(index);
  if (args['json'] != null) File(args['json']).writeAsStringSync(json);

  final String b64 = base64.encode(gzip.encode(utf8.encode(json)));
  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by tool/build_index.dart. Do not edit.')
    ..writeln('//')
    ..writeln(
      '// cairn_ui ${index['cairnUiVersion']}, ${json.length} bytes of JSON.',
    )
    ..writeln()
    ..writeln('/// The gzipped, base64-encoded knowledge index.')
    ..writeln('const String cairnIndexBase64 =');
  const int width = 96;
  for (int i = 0; i < b64.length; i += width) {
    final int end = i + width < b64.length ? i + width : b64.length;
    out.write("    '${b64.substring(i, end)}'");
    out.writeln(end == b64.length ? ';' : '');
  }
  File(args['out']).createSync(recursive: true);
  File(args['out']).writeAsStringSync(out.toString());

  final Map<String, Object?> counts = <String, Object?>{
    'modules': modules.length,
    'components': (index['components']! as List<Object?>).length,
    'docs': (index['docs']! as List<Object?>).length,
    'blocks': (index['blocks']! as List<Object?>).length,
    'templates': (index['templates']! as List<Object?>).length,
  };
  stdout.writeln('Wrote ${args['out']} ($counts, ${b64.length} base64 chars)');
}
